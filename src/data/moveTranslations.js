/**
 * Translate a move name. Strips trailing legacy markers (*, †, ‡) before lookup
 * and re-appends them. Falls back to the original FR string when no entry exists.
 */
export function translateMove(frName, lang) {
    if (!frName || lang === 'fr') return frName;
    const trailingMatch = frName.match(/([*†‡]+)$/);
    const trailing = trailingMatch ? trailingMatch[1] : '';
    const clean = (trailing ? frName.slice(0, -trailing.length) : frName).trim();
    const entry = moveTranslations[clean];
    if (!entry) return frName;
    const localized = lang === 'ja' ? entry.ja : entry.en;
    return localized ? localized + trailing : frName;
}
